using Chetah;
using Chetah.CodeGen;
using Chetah.Postgres;
using Npgsql;

namespace Chetah.CodeGen.Tests;

/// <summary>
/// Cross-component audit (audit area: end-to-end), runtime half. The table is created with the
/// exact SQL <c>chetah-db diff</c> prints for the schema below, and the metadata is built with the
/// same rules <see cref="GeneratedSource"/> applies (<c>IsNullable = column.Nullable</c>,
/// <c>HasDefault = default or identity</c>, CLR type from the type map), so schema file → DDL →
/// live column → generated metadata → compiled statement is exercised end to end.
/// </summary>
public class AuditEndToEndTests
{
    /// <summary>Table/model shape and DDL for the schema below; column order and metadata mirror the
    /// generator's output for the same file.</summary>
    private sealed record Note(int? Id, int? ParentId, string? Body);

    private static readonly string NoteTableDdl = """
        CREATE TABLE "notes" (
            "id" integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
            "parent_id" integer,
            "body" text
        );
        INSERT INTO "notes" ("body") VALUES ('seeded');
        """;

    private const string Schema = """
        { "tables": { "notes": { "columns": {
          "id": { "type": "integer", "identity": true },
          "parent_id": { "type": "integer" },
          "body": { "type": "text" } } } } }
        """;

    /// <summary>
    /// PostgreSQL makes an identity column NOT NULL (verified: `CREATE TABLE t (id integer
    /// GENERATED BY DEFAULT AS IDENTITY)` → attnotnull = true, and chetah-db emits NOT NULL for it),
    /// so the generated metadata must be <c>IsNullable = false</c>. Contract (docs/guide/insert.md,
    /// docs/project/decisions.md): an explicit NULL for a NOT NULL column is rejected before a
    /// connection opens, and an UPDATE whose value can be NULL into a NOT NULL column likewise.
    /// Both must fail as InvalidOperationException, not as PostgreSQL 23502.
    /// </summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task E2E01_ExplicitNullForIdentityColumnIsRefusedBeforeExecution()
    {
        await using var fixture = await Fixture.CreateAsync(NoteTableDdl);
        var db = fixture.Db;

        await Assert.ThrowsAsync<InvalidOperationException>(() => db.Insert<Note>()
            .Values(new { Id = (int?)null, Body = "b" })
            .ExecuteAsync());

        // The same metadata rule for UPDATE: copying a nullable column into the NOT NULL one.
        await Assert.ThrowsAsync<InvalidOperationException>(() => db.Update<Note>()
            .AllRows()
            .Set(note => note.Id, note => note.ParentId)
            .ExecuteAsync());
    }

    /// <summary>Live metadata for the schema above, built exactly as the generator emits it.</summary>
    private static IReadOnlyDictionary<Type, ITableBinding> Bindings()
    {
        var parsed = SchemaParser.Parse(Schema);
        Assert.Null(parsed.Error);
        var table = parsed.Schema!.Tables.Single();

        var columns = table.Columns.Select(column => new Column(column.Name, ClrType(column))
        {
            IsNullable = column.Nullable,
            HasDefault = column.Default is not null || column.Identity is not null,
            Generation = column.Generated is not null
                ? ColumnGeneration.Computed
                : column.Identity?.Generation == "ALWAYS" ? ColumnGeneration.Always : ColumnGeneration.None,
        }).ToArray();

        var binding = new TableBinding<Note>(
            new Table(table.Name, columns),
            reader => new Note(
                reader.IsDBNull(0) ? null : reader.GetInt32(0),
                reader.IsDBNull(1) ? null : reader.GetInt32(1),
                reader.IsDBNull(2) ? null : reader.GetString(2)),
            (reader, offset) => new Note(
                reader.IsDBNull(offset) ? null : reader.GetInt32(offset),
                reader.IsDBNull(offset + 1) ? null : reader.GetInt32(offset + 1),
                reader.IsDBNull(offset + 2) ? null : reader.GetString(offset + 2)),
            new Dictionary<string, string> { [nameof(Note.Id)] = "id", [nameof(Note.ParentId)] = "parent_id", [nameof(Note.Body)] = "body" });

        return new Dictionary<Type, ITableBinding> { [typeof(Note)] = binding };
    }

    private static Type ClrType(ColumnSchema column) => column.Type.Clr!.Name switch
    {
        "int" => typeof(int),
        "long" => typeof(long),
        "string" => typeof(string),
        "bool" => typeof(bool),
        "Guid" => typeof(Guid),
        "DateTime" => typeof(DateTime),
        _ => throw new NotSupportedException($"Unexpected CLR type {column.Type.Clr.Name} in this audit fixture."),
    };

    private sealed class Fixture : IAsyncDisposable
    {
        private readonly string _root;
        private readonly string _schema = "chetah_audit_e2e_" + Guid.NewGuid().ToString("N");

        private Fixture(string root)
        {
            _root = root;
            ConnectionString = new NpgsqlConnectionStringBuilder(root) { SearchPath = _schema }.ConnectionString;
            Db = new PostgresDb(ConnectionString, Bindings());
        }

        internal string ConnectionString { get; }

        internal PostgresDb Db { get; }

        internal static async Task<Fixture> CreateAsync(string ddl)
        {
            var root = Environment.GetEnvironmentVariable("CHETAH_CONNECTION_STRING")
                ?? throw new InvalidOperationException("Disposable PostgreSQL connection is required.");
            var fixture = new Fixture(root);

            try
            {
                await using var connection = new NpgsqlConnection(fixture.ConnectionString);
                await connection.OpenAsync();
                await using var create = new NpgsqlCommand($"CREATE SCHEMA \"{fixture._schema}\"", connection);
                await create.ExecuteNonQueryAsync();
                await using var command = new NpgsqlCommand(ddl, connection);
                await command.ExecuteNonQueryAsync();
                return fixture;
            }
            catch
            {
                await fixture.DisposeAsync();
                throw;
            }
        }

        public async ValueTask DisposeAsync()
        {
            await using var connection = new NpgsqlConnection(_root);
            await connection.OpenAsync();
            await using var drop = new NpgsqlCommand($"DROP SCHEMA \"{_schema}\" CASCADE", connection);
            await drop.ExecuteNonQueryAsync();
        }
    }
}
