using Chetah.CodeGen;
using Npgsql;

namespace Chetah.Db.Tests;

/// <summary>Regression tests for the schema→catalog→diff planning path. Every test asserts the
/// behaviour PostgreSQL requires, not the behaviour the planner currently produces.</summary>
public class AuditMigrationPlanTests
{
    private static Task<bool> NoNulls(string _, string __) => Task.FromResult(false);

    private static CatalogState Desired(string json) =>
        SchemaCatalog.FromSchema(SchemaParser.Parse(json).Schema!);

    private static int IndexOf(MigrationPlan plan, string fragment) =>
        plan.Operations.ToList().FindIndex(operation =>
            operation.Statement.Contains(fragment, StringComparison.Ordinal));

    /// <summary>PostgreSQL refuses <c>ADD GENERATED ... AS IDENTITY</c> while the column is nullable
    /// ("must be declared NOT NULL before identity can be added") or still carries a default
    /// ("already has a default value"), so both must be cleared first. Verified against PG 17.</summary>
    [Fact]
    [Trait("Category", "Audit")]
    public async Task PLAN01_IdentityIsAddedOnlyAfterNotNullAndDefaultAreCleared()
    {
        var desired = Desired("""
            { "tables": { "t": { "columns": {
              "id": { "type": "integer", "nullable": false, "identity": true } } } } }
            """);
        // A live column that is nullable and defaulted: exactly what switching a column to an
        // identity column has to migrate away from.
        var live = new CatalogState([new TableState("t", [new ColumnState("id", "int4", NotNull: false, Default: "7")])]);

        var plan = await SchemaDiff.ComputeAsync(desired, live, NoNulls);

        var identity = IndexOf(plan, "ADD GENERATED BY DEFAULT AS IDENTITY");
        var notNull = IndexOf(plan, "SET NOT NULL");
        var dropDefault = IndexOf(plan, "DROP DEFAULT");

        Assert.True(identity >= 0, "the plan is expected to add the identity");
        Assert.True(notNull >= 0, "the plan is expected to set NOT NULL first");
        Assert.True(dropDefault >= 0, "the plan is expected to drop the default first");
        Assert.True(notNull < identity, "SET NOT NULL must precede ADD GENERATED ... AS IDENTITY");
        Assert.True(dropDefault < identity, "DROP DEFAULT must precede ADD GENERATED ... AS IDENTITY");
    }

    /// <summary>The same prerequisite, end to end: converting a nullable column to an identity column
    /// is a documented supported operation and must apply.</summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task PLAN01_IdentityOnANullableColumnApplies()
    {
        await using var fixture = await Fixture.CreateAsync();
        const string nullable = """
            { "tables": { "w": { "columns": {
              "id": { "type": "integer" },
              "payload": { "type": "text" } } } } }
            """;

        Assert.Equal(0, await fixture.Runner(new StringWriter()).ApplyAsync(fixture.Parse(nullable)));

        var identity = nullable.Replace("\"type\": \"integer\" }", "\"type\": \"integer\", \"identity\": true }");
        var output = new StringWriter();
        var code = await fixture.Runner(output).ApplyAsync(fixture.Parse(identity));
        Assert.True(code == 0, output.ToString());

        Assert.Equal("YES", (string?)await fixture.ScalarAsync(
            "SELECT is_identity FROM information_schema.columns "
            + "WHERE table_schema = 'public' AND table_name = 'w' AND column_name = 'id'"));
        Assert.Equal("NO", (string?)await fixture.ScalarAsync(
            "SELECT is_nullable FROM information_schema.columns "
            + "WHERE table_schema = 'public' AND table_name = 'w' AND column_name = 'id'"));
    }

    /// <summary>A column that already holds a default cannot take an identity before the default is
    /// dropped (PG: "column ... already has a default value").</summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task PLAN01_IdentityReplacingADefaultApplies()
    {
        await using var fixture = await Fixture.CreateAsync();
        const string withDefault = """
            { "tables": { "w": { "columns": {
              "id": { "type": "integer", "nullable": false, "default": 5 },
              "payload": { "type": "text" } } } } }
            """;

        Assert.Equal(0, await fixture.Runner(new StringWriter()).ApplyAsync(fixture.Parse(withDefault)));

        var identity = withDefault.Replace("\"default\": 5", "\"identity\": true");
        var output = new StringWriter();
        var code = await fixture.Runner(output).ApplyAsync(fixture.Parse(identity));
        Assert.True(code == 0, output.ToString());

        Assert.Equal("YES", (string?)await fixture.ScalarAsync(
            "SELECT is_identity FROM information_schema.columns "
            + "WHERE table_schema = 'public' AND table_name = 'w' AND column_name = 'id'"));
        Assert.Equal(DBNull.Value, await fixture.ScalarAsync(
            "SELECT column_default FROM information_schema.columns "
            + "WHERE table_schema = 'public' AND table_name = 'w' AND column_name = 'id'") ?? DBNull.Value);
    }

    /// <summary>A partition is owned by its partitioned table (<c>pg_class.relkind = 'p'</c>), which
    /// the catalog reader does not read at all. A partition is therefore never a table the schema file
    /// "removed": planning <c>DROP TABLE</c> for it would delete rows of a table the file cannot even
    /// describe, so the object has to be reported as unexpressible instead.</summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task PLAN02_APartitionIsNotPlannedAsAnUnmanagedTableToDrop()
    {
        await using var fixture = await Fixture.CreateAsync();
        await fixture.ExecuteAsync("""
            CREATE TABLE events (id bigint NOT NULL, at timestamp NOT NULL) PARTITION BY RANGE (id);
            CREATE TABLE events_p1 PARTITION OF events FOR VALUES FROM (0) TO (100);
            INSERT INTO events VALUES (1, now());
            """);

        var desired = Desired("""{ "tables": { "unrelated": { "columns": { "id": { "type": "integer" } } } } }""");
        var plan = await PlanAsync(fixture, desired);

        Assert.DoesNotContain(plan.Operations, operation =>
            operation.Target?.Kind == OperationKinds.DropTable && operation.Target.Table == "events_p1");
    }

    /// <summary>The same blind spot seen from the other side: a relation the file declares is already
    /// there as a partitioned table, so the plan must not emit <c>CREATE TABLE</c> for it (PostgreSQL
    /// answers 42P07 "relation already exists"); it has to be refused as unsupported instead.</summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task PLAN02_APartitionedParentIsNotPlannedAsCreate()
    {
        await using var fixture = await Fixture.CreateAsync();
        await fixture.ExecuteAsync("""
            CREATE TABLE events (id bigint NOT NULL, at timestamp NOT NULL) PARTITION BY RANGE (id);
            CREATE TABLE events_p1 PARTITION OF events FOR VALUES FROM (0) TO (100);
            """);

        var desired = Desired("""
            { "tables": { "events": { "columns": {
              "id": { "type": "bigint", "nullable": false },
              "at": { "type": "timestamp", "nullable": false } } } } }
            """);
        var plan = await PlanAsync(fixture, desired);

        Assert.DoesNotContain(plan.Operations, operation =>
            operation.Target?.Kind == OperationKinds.CreateTable && operation.Target.Table == "events");
    }

    /// <summary>PostgreSQL keeps the index behind a unique constraint in the schema's relation
    /// namespace, so a declared index and a declared constraint cannot carry the same name: the plan
    /// creates both and the second statement fails with 42P07. Constraint names are cross-checked
    /// against each other for exactly this reason, so this collision must be reported too.</summary>
    [Fact]
    [Trait("Category", "Audit")]
    public void PLAN03_DeclaredIndexNameCollidingWithAConstraintNameIsRejected()
    {
        var parsed = SchemaParser.Parse("""
            { "$schema": "./chetah.schema.json", "tables": { "t": {
              "columns": { "a": { "type": "integer" }, "b": { "type": "integer" } },
              "unique": [{ "name": "t_shared", "columns": ["a"] }],
              "indexes": [{ "name": "t_shared", "keys": [{ "column": "b" }] }] } } }
            """);

        Assert.NotNull(parsed.Error);
    }

    private static async Task<MigrationPlan> PlanAsync(Fixture fixture, CatalogState desired)
    {
        await using var connection = new NpgsqlConnection(fixture.ConnectionString);
        await connection.OpenAsync();
        var live = await PostgresCatalog.ReadAsync(connection, "public", CancellationToken.None);
        return await SchemaDiff.ComputeAsync(desired, live, NoNulls);
    }

    /// <summary>A throwaway database per test, in the shape the other live tests use: the internal
    /// <c>chetah</c> schema is global to a database, so tests cannot share one.</summary>
    private sealed class Fixture : IAsyncDisposable
    {
        private readonly string _root;
        private readonly string _database = "audit_plan_" + Guid.NewGuid().ToString("N");

        private Fixture(string root)
        {
            _root = root;
            ConnectionString = new NpgsqlConnectionStringBuilder(root) { Database = _database }.ConnectionString;
        }

        internal string ConnectionString { get; }

        internal string MigrationsDirectory { get; } =
            Path.Combine(Path.GetTempPath(), "audit-plan-migrations-" + Guid.NewGuid().ToString("N"));

        internal string SchemaPath { get; } =
            Path.Combine(Path.GetTempPath(), "audit-plan-schema-" + Guid.NewGuid().ToString("N") + ".json");

        internal static async Task<Fixture> CreateAsync()
        {
            var root = Environment.GetEnvironmentVariable("CHETAH_CONNECTION_STRING")
                ?? throw new InvalidOperationException("Disposable PostgreSQL connection is required.");
            var fixture = new Fixture(root);

            await using var connection = new NpgsqlConnection(root);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand($"CREATE DATABASE \"{fixture._database}\"", connection);
            await command.ExecuteNonQueryAsync();
            return fixture;
        }

        internal Schema Parse(string json)
        {
            File.WriteAllText(SchemaPath, json);
            var parsed = SchemaParser.Parse(json);
            Assert.Null(parsed.Error);
            return parsed.Schema!;
        }

        internal MigrationRunner Runner(StringWriter output) =>
            new(ConnectionString, SchemaPath, MigrationsDirectory, output, _ => true);

        internal async Task ExecuteAsync(string sql)
        {
            await using var connection = new NpgsqlConnection(ConnectionString);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand(sql, connection);
            await command.ExecuteNonQueryAsync();
        }

        internal async Task<object?> ScalarAsync(string sql)
        {
            await using var connection = new NpgsqlConnection(ConnectionString);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand(sql, connection);
            return await command.ExecuteScalarAsync();
        }

        public async ValueTask DisposeAsync()
        {
            try
            {
                await using var connection = new NpgsqlConnection(_root);
                await connection.OpenAsync();
                await using var command = new NpgsqlCommand(
                    $"DROP DATABASE IF EXISTS \"{_database}\" WITH (FORCE)",
                    connection);
                await command.ExecuteNonQueryAsync();
            }
            finally
            {
                if (Directory.Exists(MigrationsDirectory))
                    Directory.Delete(MigrationsDirectory, recursive: true);
            }
        }
    }
}
