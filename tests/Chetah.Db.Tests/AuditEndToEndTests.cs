using Chetah.CodeGen;
using Npgsql;

namespace Chetah.Db.Tests;

/// <summary>
/// Cross-component audit (audit area: end-to-end). Each fact walks the same object through the
/// representations the product claims are one truth: schema file → migration DDL → live PostgreSQL
/// catalog → generated model/metadata.
/// </summary>
public class AuditEndToEndTests
{
    /// <summary>
    /// An identity column is NOT NULL in PostgreSQL whether or not the file says so, and the
    /// migration engine already encodes that rule (Catalog.ToState: "column.Identity is not null ||
    /// !column.Nullable", so CREATE TABLE emits NOT NULL explicitly).
    ///
    /// Verified against PostgreSQL 17.11: `CREATE TABLE t (id integer GENERATED BY DEFAULT AS
    /// IDENTITY)` reports attnotnull = true. The generated metadata must therefore say
    /// `IsNullable = false` and expose `int`, otherwise the INSERT/UPDATE compilers accept an
    /// explicit NULL for a column the database rejects (documented contract: an explicit NULL for a
    /// NOT NULL column is rejected before execution — docs/guide/insert.md, "Omitted, NULL and
    /// DEFAULT are different").
    /// </summary>
    [PostgresFact]
    [Trait("Category", "Audit")]
    public async Task E2E01_IdentityColumnIsNotNullInEveryRepresentation()
    {
        await using var fixture = await Fixture.CreateAsync();

        // The shorthand documented in docs/guide/writing-a-schema.md ("## Identity"): the file does
        // not say "nullable": false, so the model currently keeps the PostgreSQL column default
        // (nullable) even though an identity column cannot be nullable.
        const string json = """
            { "tables": { "notes": { "columns": {
              "id": { "type": "integer", "identity": true },
              "body": { "type": "text" } } } } }
            """;

        var parsed = fixture.Parse(json);
        Assert.Equal(0, await fixture.Runner().ApplyAsync(parsed));

        // 1. Live catalog: PostgreSQL made the identity column NOT NULL on its own.
        Assert.Equal("NO", await fixture.ScalarAsync("""
            SELECT is_nullable FROM information_schema.columns
            WHERE table_schema = 'public' AND table_name = 'notes' AND column_name = 'id'
            """));

        // 2. Generated metadata must agree with the live column.
        var source = GeneratedSource.Render(parsed, "Audit.EndToEnd");
        var idField = Assert.Single(source.Split('\n'), line => line.Contains(" Id = new(\"id\")", StringComparison.Ordinal));
        Assert.Contains("Chetah.Column<int> Id", idField, StringComparison.Ordinal);
        Assert.Contains("IsNullable = false", idField, StringComparison.Ordinal);

        // 3. Root cause: the parsed model itself still calls the column nullable.
        var id = Assert.Single(parsed.Tables[0].Columns, column => column.Name == "id");
        Assert.False(id.Nullable);
    }

    private sealed class Fixture : IAsyncDisposable
    {
        private readonly string _root;
        private readonly string _database = "chetah_audit_e2e_" + Guid.NewGuid().ToString("N");

        private Fixture(string root)
        {
            _root = root;
            ConnectionString = new NpgsqlConnectionStringBuilder(root) { Database = _database }.ConnectionString;
        }

        internal string ConnectionString { get; }

        internal string MigrationsDirectory { get; } =
            Path.Combine(Path.GetTempPath(), "chetah-audit-e2e-migrations-" + Guid.NewGuid().ToString("N"));

        internal string SchemaPath { get; } =
            Path.Combine(Path.GetTempPath(), "chetah-audit-e2e-schema-" + Guid.NewGuid().ToString("N") + ".json");

        internal static async Task<Fixture> CreateAsync()
        {
            var root = Environment.GetEnvironmentVariable("CHETAH_CONNECTION_STRING")
                ?? throw new InvalidOperationException("Disposable PostgreSQL connection is required.");
            var fixture = new Fixture(root);

            await using var connection = new NpgsqlConnection(root);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand($"CREATE DATABASE \"{fixture._database}\"", connection);
            await command.ExecuteNonQueryAsync();
            return fixture;
        }

        /// <summary>Writes the declaration where the runner persists "$id" and parses it.</summary>
        internal Schema Parse(string json)
        {
            File.WriteAllText(SchemaPath, json);
            var parsed = SchemaParser.Parse(json);
            Assert.Null(parsed.Error);
            return parsed.Schema!;
        }

        internal MigrationRunner Runner() =>
            new(ConnectionString, SchemaPath, MigrationsDirectory, new StringWriter(), _ => true);

        internal async Task<object?> ScalarAsync(string sql)
        {
            await using var connection = new NpgsqlConnection(ConnectionString);
            await connection.OpenAsync();
            await using var command = new NpgsqlCommand(sql, connection);
            return await command.ExecuteScalarAsync();
        }

        public async ValueTask DisposeAsync()
        {
            try
            {
                await using var connection = new NpgsqlConnection(_root);
                await connection.OpenAsync();
                await using var command = new NpgsqlCommand(
                    $"DROP DATABASE IF EXISTS \"{_database}\" WITH (FORCE)", connection);
                await command.ExecuteNonQueryAsync();
            }
            finally
            {
                if (Directory.Exists(MigrationsDirectory))
                    Directory.Delete(MigrationsDirectory, recursive: true);
                if (File.Exists(SchemaPath))
                    File.Delete(SchemaPath);
            }
        }
    }
}
