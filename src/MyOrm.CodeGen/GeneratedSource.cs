using System.Text;

namespace MyOrm.CodeGen;

/// <summary>Renders the generated C# source for a parsed schema. Pure text in, single file out.</summary>
public static class GeneratedSource
{
    public static string Render(Schema schema, string @namespace)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     Generated by MyOrm.CodeGen from the schema file. Do not edit by hand:");
        sb.AppendLine("//     rerun the generator instead (dotnet run --project src/MyOrm.CodeGen …).");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using Npgsql;");
        sb.AppendLine();
        sb.AppendLine($"namespace {@namespace};");
        sb.AppendLine();

        foreach (var table in schema.Tables)
            RenderTable(sb, table);

        RenderRegistry(sb, schema);

        return sb.ToString();
    }

    /// <summary>The Type→binding registry the consumer passes to PostgresDb.</summary>
    private static void RenderRegistry(StringBuilder sb, Schema schema)
    {
        sb.AppendLine("public static class MyOrmSchema");
        sb.AppendLine("{");

        foreach (var table in schema.Tables)
            sb.AppendLine(
                $"    public static readonly MyOrm.Postgres.TableBinding<{table.ModelName}> {table.ModelName}Binding = new({table.AccessorName}.Table, {table.AccessorName}.Map);");

        sb.AppendLine();
        sb.AppendLine("    public static readonly System.Collections.Generic.IReadOnlyDictionary<System.Type, MyOrm.Postgres.ITableBinding> Bindings =");
        sb.AppendLine("        new System.Collections.Generic.Dictionary<System.Type, MyOrm.Postgres.ITableBinding>");
        sb.AppendLine("        {");
        foreach (var table in schema.Tables)
            sb.AppendLine($"            [typeof({table.ModelName})] = {table.ModelName}Binding,");
        sb.AppendLine("        };");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void RenderTable(StringBuilder sb, TableSchema table)
    {
        sb.AppendLine($"public static class {table.AccessorName}");
        sb.AppendLine("{");

        foreach (var column in table.Columns)
            sb.AppendLine(
                $"    public static readonly MyOrm.Column<{PropertyType(column)}> {Identifier(column.Name)} = new({CSharpStringLiteral(column.Name)});");

        sb.AppendLine();
        sb.AppendLine(
            "    public static readonly MyOrm.Table Table = new("
            + CSharpStringLiteral(table.Name) + ", "
            + string.Join(", ", table.Columns.Select(c => Identifier(c.Name) + ".Name"))
            + ");");
        sb.AppendLine();
        RenderMap(sb, table);
        sb.AppendLine("}");
        sb.AppendLine();

        var properties = string.Join(", ", table.Columns.Select(c => $"{PropertyType(c)} {Identifier(c.Name)}"));
        sb.AppendLine($"public sealed record {table.ModelName}({properties});");
        sb.AppendLine();
    }

    /// <summary>Generated mapper with one ordinal per nullable column, one expression per property.</summary>
    private static void RenderMap(StringBuilder sb, TableSchema table)
    {
        sb.AppendLine($"    public static {table.ModelName} Map(NpgsqlDataReader reader)");
        sb.AppendLine("    {");

        foreach (var nullable in table.Columns.Where(c => c.Nullable))
            sb.AppendLine($"        var {OrdinalLocal(nullable.Name)} = reader.GetOrdinal({CSharpStringLiteral(nullable.Name)});");

        if (table.Columns.Any(c => c.Nullable))
            sb.AppendLine();

        sb.AppendLine("        return new " + table.ModelName + "(");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var expression = column.Nullable
                ? $"reader.IsDBNull({OrdinalLocal(column.Name)}) ? null : {string.Format(column.Type.Read, OrdinalLocal(column.Name))}"
                : string.Format(column.Type.Read, $"reader.GetOrdinal({CSharpStringLiteral(column.Name)})");
            var comma = i == table.Columns.Count - 1 ? "" : ",";
            sb.AppendLine($"            {expression}{comma}");
        }
        sb.AppendLine("        );");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    private static string PropertyType(ColumnSchema column) =>
        column.Nullable ? column.Type.NullableName : column.Type.Name;

    private static string Identifier(string name)
    {
        var pascal = SchemaParser.PascalCase(name);
        return pascal.Length == 0 || !char.IsLetter(pascal[0]) || !pascal.All(char.IsLetterOrDigit)
            ? "@" + pascal
            : pascal;
    }

    private static string OrdinalLocal(string name)
    {
        var camel = CamelCase(name);
        return camel.Length > 0 && (char.IsLetter(camel[0]) || camel[0] == '_')
            && camel.All(c => char.IsLetterOrDigit(c) || c == '_')
            ? camel + "Ordinal"
            : "@" + camel + "Ordinal";
    }

    private static string CamelCase(string identifier)
    {
        var pascal = SchemaParser.PascalCase(identifier);
        return pascal.Length == 0 ? "_" : char.ToLowerInvariant(pascal[0]) + pascal[1..];
    }

    /// <summary>Proper C# string literal — schema names are validated identifiers, so
    /// this only ever escapes \" and \\ sequences.</summary>
    private static string CSharpStringLiteral(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
