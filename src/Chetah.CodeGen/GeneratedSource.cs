using System.Globalization;
using System.Text;

namespace Chetah.CodeGen;

/// <summary>Renders the generated C# source for a parsed schema. Pure text in, files out.</summary>
public static class GeneratedSource
{
    /// <summary>The shared registry file; also the whole output of the single layout.</summary>
    public const string SharedFileName = "Chetah.Schema.g.cs";

    /// <summary>Renders the single-file layout, kept as a public entry point for existing consumers.</summary>
    public static string Render(Schema schema, string @namespace) =>
        RenderFiles(schema, @namespace, GeneratedLayout.Single).Single().Content;

    /// <summary>Renders every file for <paramref name="layout"/>, relative to the output directory.</summary>
    public static IReadOnlyList<GeneratedFile> RenderFiles(
        Schema schema,
        string @namespace,
        GeneratedLayout layout)
    {
        ValidateClrMappings(schema);
        ValidateGeneratedNames(schema);

        return layout == GeneratedLayout.Single
            ? [new GeneratedFile(SharedFileName, RenderSingle(schema, @namespace))]
            : RenderSplit(schema, @namespace);
    }

    private static IReadOnlyList<GeneratedFile> RenderSplit(Schema schema, string @namespace)
    {
        var files = new List<GeneratedFile>
        {
            new(SharedFileName, RenderSharedRegistry(schema, @namespace)),
        };

        foreach (var table in schema.Tables)
            files.Add(new GeneratedFile($"Tables/{table.Name}.g.cs", RenderTableFile(table, @namespace)));

        foreach (var @enum in schema.Enums ?? [])
            files.Add(new GeneratedFile($"Enums/{EnumFileStem(@enum)}.g.cs", RenderEnumFile(@enum, @namespace)));

        return files;
    }

    private static string RenderSingle(Schema schema, string @namespace)
    {
        var sb = new StringBuilder();
        AppendHeader(sb);
        AppendNpgsqlUsing(sb);
        AppendNamespace(sb, @namespace);

        foreach (var @enum in schema.Enums ?? [])
            RenderEnum(sb, @enum);

        foreach (var table in schema.Tables)
            RenderTable(sb, table);

        RenderRegistry(sb, schema, partial: false);
        return sb.ToString();
    }

    private static string RenderSharedRegistry(Schema schema, string @namespace)
    {
        var sb = new StringBuilder();
        AppendHeader(sb);
        AppendNamespace(sb, @namespace);
        RenderRegistry(sb, schema, partial: true);
        return sb.ToString();
    }

    private static string RenderTableFile(TableSchema table, string @namespace)
    {
        var sb = new StringBuilder();
        AppendHeader(sb);
        AppendNpgsqlUsing(sb);
        AppendNamespace(sb, @namespace);
        RenderTable(sb, table);

        sb.AppendLine("public static partial class ChetahSchema");
        sb.AppendLine("{");
        sb.AppendLine("    " + BindingField(table));
        sb.AppendLine("}");
        sb.AppendLine();

        return sb.ToString();
    }

    private static string RenderEnumFile(EnumSchema @enum, string @namespace)
    {
        var sb = new StringBuilder();
        AppendHeader(sb);
        AppendNamespace(sb, @namespace);
        RenderEnum(sb, @enum);
        return sb.ToString();
    }

    private static void AppendHeader(StringBuilder sb)
    {
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//     Generated by Chetah.CodeGen from the schema file. Do not edit by hand:");
        sb.AppendLine("//     rerun the generator instead (dotnet run --project src/Chetah.CodeGen …).");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
    }

    private static void AppendNpgsqlUsing(StringBuilder sb)
    {
        sb.AppendLine("using Npgsql;");
        sb.AppendLine();
    }

    private static void AppendNamespace(StringBuilder sb, string @namespace)
    {
        sb.AppendLine($"namespace {@namespace};");
        sb.AppendLine();
    }

    /// <summary>The Type→binding registry the consumer passes to PostgresDb.</summary>
    private static void RenderRegistry(StringBuilder sb, Schema schema, bool partial)
    {
        sb.AppendLine(partial ? "public static partial class ChetahSchema" : "public static class ChetahSchema");
        sb.AppendLine("{");

        if (!partial)
        {
            foreach (var table in schema.Tables)
                sb.AppendLine("    " + BindingField(table));
            sb.AppendLine();
        }

        sb.AppendLine("    static ChetahSchema()");
        sb.AppendLine("    {");
        sb.AppendLine("        Bindings = new System.Collections.Generic.Dictionary<System.Type, Chetah.Postgres.ITableBinding>");
        sb.AppendLine("        {");
        foreach (var table in schema.Tables)
            sb.AppendLine($"            [typeof({table.ModelName})] = {table.ModelName}Binding,");
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine(
            "    public static readonly System.Collections.Generic.IReadOnlyDictionary<System.Type, Chetah.Postgres.ITableBinding> Bindings;");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static string BindingField(TableSchema table) =>
        $"public static readonly Chetah.Postgres.TableBinding<{table.ModelName}> {table.ModelName}Binding = "
        + $"new({table.AccessorName}.Table, {table.AccessorName}.Map, {table.AccessorName}.MapAt, "
        + $"{table.AccessorName}.PropertyColumns);";

    private static void RenderEnum(StringBuilder sb, EnumSchema @enum)
    {
        var qualified = $"{@enum.Schema}.{@enum.Name}";
        sb.AppendLine($"/// <summary>Labels of the PostgreSQL enum <c>{qualified}</c>, in declaration order.</summary>");
        sb.AppendLine($"public static class {EnumTypeName(@enum)}");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly System.Collections.Generic.IReadOnlyList<string> Values = new string[]");
        sb.AppendLine("    {");
        foreach (var value in @enum.Values)
            sb.AppendLine($"        {CSharpStringLiteral(value)},");
        sb.AppendLine("    };");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void RenderTable(StringBuilder sb, TableSchema table)
    {
        sb.AppendLine($"public static class {table.AccessorName}");
        sb.AppendLine("{");

        foreach (var column in table.Columns)
            sb.AppendLine(
                $"    public static readonly Chetah.Column<{PropertyType(column)}> {Identifier(column.Name)} = new({CSharpStringLiteral(column.Name)});");

        sb.AppendLine();
        sb.AppendLine(
            "    public static readonly Chetah.Table Table = new("
            + CSharpStringLiteral(table.Name) + ", "
            + string.Join(", ", table.Columns.Select(c => Identifier(c.Name) + ".Name"))
            + ");");
        sb.AppendLine();
        sb.AppendLine("    public static readonly System.Collections.Generic.IReadOnlyDictionary<string, string> PropertyColumns =");
        sb.AppendLine("        new System.Collections.Generic.Dictionary<string, string>(System.StringComparer.Ordinal)");
        sb.AppendLine("        {");
        foreach (var column in table.Columns)
            sb.AppendLine($"            [nameof({table.ModelName}.{Identifier(column.Name)})] = {CSharpStringLiteral(column.Name)},");
        sb.AppendLine("        };");
        sb.AppendLine();

        RenderMap(sb, table);
        RenderMapAt(sb, table);
        sb.AppendLine("}");
        sb.AppendLine();

        var properties = string.Join(", ", table.Columns.Select(c => $"{PropertyType(c)} {Identifier(c.Name)}"));
        sb.AppendLine($"public sealed record {table.ModelName}({properties});");
        sb.AppendLine();
    }

    /// <summary>Generated mapper with one ordinal per nullable column, one expression per property.</summary>
    private static void RenderMap(StringBuilder sb, TableSchema table)
    {
        sb.AppendLine($"    public static {table.ModelName} Map(NpgsqlDataReader reader)");
        sb.AppendLine("    {");

        foreach (var nullable in table.Columns.Where(c => c.Nullable))
            sb.AppendLine($"        var {OrdinalLocal(nullable.Name)} = reader.GetOrdinal({CSharpStringLiteral(nullable.Name)});");

        if (table.Columns.Any(c => c.Nullable))
            sb.AppendLine();

        RenderReads(sb, table, (column, _) => column.Nullable
            ? OrdinalLocal(column.Name)
            : $"reader.GetOrdinal({CSharpStringLiteral(column.Name)})");

        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>Generated mapper keyed by schema order at an ordinal offset, for projected/joined results.</summary>
    private static void RenderMapAt(StringBuilder sb, TableSchema table)
    {
        sb.AppendLine($"    public static {table.ModelName} MapAt(NpgsqlDataReader reader, int offset)");
        sb.AppendLine("    {");
        RenderReads(sb, table, (_, index) => $"offset + {index}");
        sb.AppendLine("    }");
        sb.AppendLine();
    }

    /// <summary>Shared constructor argument list: one read expression per schema column.</summary>
    private static void RenderReads(StringBuilder sb, TableSchema table, Func<ColumnSchema, int, string> ordinal)
    {
        sb.AppendLine("        return new " + table.ModelName + "(");
        for (var i = 0; i < table.Columns.Count; i++)
        {
            var column = table.Columns[i];
            var ord = ordinal(column, i);
            var expression = column.Nullable
                ? $"reader.IsDBNull({ord}) ? null : {string.Format(column.Type.Clr!.Read, ord)}"
                : string.Format(column.Type.Clr!.Read, ord);
            var comma = i == table.Columns.Count - 1 ? "" : ",";
            sb.AppendLine($"            {expression}{comma}");
        }
        sb.AppendLine("        );");
    }

    private static void ValidateClrMappings(Schema schema)
    {
        foreach (var table in schema.Tables)
        {
            foreach (var column in table.Columns.Where(column => !column.Type.CanGenerate))
            {
                throw new InvalidOperationException(
                    $"Table '{table.Name}': column '{column.Name}' has type '{column.Type.SqlType}', which has no "
                    + "CLR mapping. Use a built-in PostgreSQL type (or an enum declared in this file), or keep "
                    + "that column out of the generated models.");
            }
        }
    }

    /// <summary>Generated C# types and file names must be unique, including under the
    /// case-insensitive comparison Windows applies to file names.</summary>
    private static void ValidateGeneratedNames(Schema schema)
    {
        var types = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            ["ChetahSchema"] = "the generated registry class",
        };
        var files = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
        {
            [SharedFileName] = "the shared registry file",
        };

        foreach (var table in schema.Tables)
        {
            Reserve(types, table.ModelName, $"table '{table.Name}' model");
            Reserve(types, table.AccessorName, $"table '{table.Name}' accessor");
            Reserve(files, $"Tables/{table.Name}.g.cs", $"table '{table.Name}'");
        }

        foreach (var @enum in schema.Enums ?? [])
        {
            var typeName = EnumTypeName(@enum);
            if (!SchemaParser.IsValidIdentifier(typeName))
                throw new InvalidOperationException(
                    $"Enum '{QualifiedEnumName(@enum)}' cannot produce a valid C# type name ('{typeName}'). Rename the enum.");

            Reserve(types, typeName, $"enum '{QualifiedEnumName(@enum)}'");
            Reserve(files, $"Enums/{EnumFileStem(@enum)}.g.cs", $"enum '{QualifiedEnumName(@enum)}'");
        }
    }

    private static void Reserve(
        Dictionary<string, string> used,
        string name,
        string description)
    {
        if (used.TryGetValue(name, out var existing))
            throw new InvalidOperationException(
                $"Generated name '{name}' for {description} collides with {existing}. Rename one of them.");

        used.Add(name, description);
    }

    private static string EnumTypeName(EnumSchema @enum) =>
        SchemaParser.PascalCase(@enum.Schema == "public" ? @enum.Name : $"{@enum.Schema}_{@enum.Name}");

    private static string EnumFileStem(EnumSchema @enum) =>
        @enum.Schema == "public" ? @enum.Name : $"{@enum.Schema}_{@enum.Name}";

    private static string QualifiedEnumName(EnumSchema @enum) =>
        @enum.Schema == "public" ? @enum.Name : $"{@enum.Schema}.{@enum.Name}";

    private static string PropertyType(ColumnSchema column) =>
        column.Nullable ? column.Type.Clr!.NullableName : column.Type.Clr!.Name;

    private static string Identifier(string name)
    {
        var pascal = SchemaParser.PascalCase(name);
        return pascal.Length == 0 || !char.IsLetter(pascal[0]) || !pascal.All(char.IsLetterOrDigit)
            ? "@" + pascal
            : pascal;
    }

    private static string OrdinalLocal(string name)
    {
        var camel = CamelCase(name);
        return camel.Length > 0 && (char.IsLetter(camel[0]) || camel[0] == '_')
            && camel.All(c => char.IsLetterOrDigit(c) || c == '_')
            ? camel + "Ordinal"
            : "@" + camel + "Ordinal";
    }

    private static string CamelCase(string identifier)
    {
        var pascal = SchemaParser.PascalCase(identifier);
        return pascal.Length == 0 ? "_" : char.ToLowerInvariant(pascal[0]) + pascal[1..];
    }

    /// <summary>Proper C# string literal. Table and column names are validated identifiers, but
    /// enum labels are arbitrary non-empty strings, so control and line-separator characters are
    /// escaped rather than emitted raw.</summary>
    private static string CSharpStringLiteral(string value)
    {
        var literal = new StringBuilder(value.Length + 2);
        literal.Append('"');
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\': literal.Append("\\\\"); break;
                case '"': literal.Append("\\\""); break;
                case '\0': literal.Append("\\0"); break;
                case '\a': literal.Append("\\a"); break;
                case '\b': literal.Append("\\b"); break;
                case '\f': literal.Append("\\f"); break;
                case '\n': literal.Append("\\n"); break;
                case '\r': literal.Append("\\r"); break;
                case '\t': literal.Append("\\t"); break;
                case '\v': literal.Append("\\v"); break;
                default:
                    if (char.IsControl(character) || character is '\u2028' or '\u2029')
                        literal.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    else
                        literal.Append(character);
                    break;
            }
        }

        literal.Append('"');
        return literal.ToString();
    }
}
