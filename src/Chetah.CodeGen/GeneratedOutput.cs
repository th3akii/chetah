using System.Text;
using System.Text.Json;

namespace Chetah.CodeGen;

/// <summary>How generated types are organized on disk.</summary>
public enum GeneratedLayout
{
    /// <summary>One file per table and enum, plus a small shared registry file.</summary>
    Split,

    /// <summary>Every generated type in a single file, for consumers that expect the original layout.</summary>
    Single,
}

/// <summary>One rendered file, addressed relative to the output directory with <c>/</c> separators.</summary>
public sealed record GeneratedFile(string RelativePath, string Content);

/// <summary>What a regeneration actually changed on disk.</summary>
/// <param name="Written">Relative paths written in this run, sorted ordinally.</param>
/// <param name="Deleted">Obsolete generated paths removed in this run, sorted ordinally.</param>
/// <param name="Preserved">Manifest paths that no longer belong to the generated set but were left
/// alone because the file no longer carries the generated marker.</param>
public sealed record GeneratedOutputResult(
    IReadOnlyList<string> Written,
    IReadOnlyList<string> Deleted,
    IReadOnlyList<string> Preserved);

/// <summary>Writes rendered files and maintains the ownership manifest that makes regeneration safe.</summary>
public static class GeneratedOutput
{
    public const string ManifestFileName = ".chetah-codegen.json";

    private const int ManifestVersion = 1;
    private const string GeneratedMarker = "// <auto-generated>";

    private static readonly HashSet<string> ReservedDeviceNames = new(StringComparer.OrdinalIgnoreCase)
    {
        "CON", "PRN", "AUX", "NUL",
        "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9",
        "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9",
    };

    private static readonly char[] InvalidFileNameCharacters = ['<', '>', ':', '"', '/', '\\', '|', '?', '*'];

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        ReadCommentHandling = JsonCommentHandling.Skip,
        AllowTrailingCommas = true,
        WriteIndented = true,
        NewLine = "\n",
    };

    /// <summary>Writes <paramref name="files"/> and removes files owned by a previous generation that
    /// are no longer declared. Rendering and every validation run before the first byte is written.</summary>
    public static async Task<GeneratedOutputResult> WriteAsync(
        string outputDirectory,
        string @namespace,
        GeneratedLayout layout,
        IReadOnlyList<GeneratedFile> files,
        CancellationToken cancellationToken = default)
    {
        if (string.IsNullOrWhiteSpace(outputDirectory))
            throw new InvalidOperationException("The output directory must not be empty.");

        var root = Path.GetFullPath(outputDirectory);
        if (File.Exists(root))
            throw new InvalidOperationException($"Output path '{outputDirectory}' is a file, not a directory.");

        var desired = new SortedDictionary<string, GeneratedFile>(StringComparer.Ordinal);
        var pathsByCase = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        foreach (var file in files)
        {
            var relative = NormalizeRelativePath(file.RelativePath);
            if (string.Equals(relative, ManifestFileName, StringComparison.OrdinalIgnoreCase))
                throw new InvalidOperationException($"Generated file '{relative}' uses the manifest name.");

            if (!desired.TryAdd(relative, file with { RelativePath = relative }))
                throw new InvalidOperationException($"Generated file '{relative}' is declared more than once.");

            if (!pathsByCase.TryAdd(relative, relative))
                throw new InvalidOperationException(
                    $"Generated files '{pathsByCase[relative]}' and '{relative}' differ only by case, "
                    + "which collides on Windows. Rename one declaration.");
        }

        var manifestPath = Path.Combine(root, ManifestFileName);
        var previous = await ReadManifestAsync(manifestPath, cancellationToken);

        // A user file at a generated path is never clobbered; validating every target before staging
        // also means a refusal leaves the output directory untouched.
        foreach (var relative in desired.Keys)
        {
            var target = FullPath(root, relative);
            if (Directory.Exists(target))
                throw new InvalidOperationException(
                    $"Cannot write generated file '{target}': a directory with that name exists.");

            if (File.Exists(target) && !await StartsWithGeneratedMarkerAsync(target, cancellationToken))
                throw new InvalidOperationException(
                    $"Refusing to overwrite '{target}': it is not marked as generated by Chetah.CodeGen. "
                    + "Move that file or choose a different --out directory.");
        }

        var stale = (previous.Files ?? [])
            .Where(path => !desired.ContainsKey(path))
            .OrderBy(path => path, StringComparer.Ordinal)
            .ToList();

        // Stage every file first so a failed write does not truncate an existing generated file.
        Directory.CreateDirectory(root);
        var staged = new List<(string Temporary, string Target)>();
        try
        {
            foreach (var (relative, file) in desired)
            {
                var target = FullPath(root, relative);
                Directory.CreateDirectory(Path.GetDirectoryName(target)!);
                var temporary = target + ".tmp-" + Guid.NewGuid().ToString("N");
                await File.WriteAllTextAsync(temporary, file.Content, new UTF8Encoding(false), cancellationToken);
                staged.Add((temporary, target));
            }

            foreach (var (temporary, target) in staged)
                File.Move(temporary, target, overwrite: true);
        }
        catch
        {
            foreach (var (temporary, _) in staged.Where(item => File.Exists(item.Temporary)))
                File.Delete(temporary);
            throw;
        }

        var deleted = new List<string>();
        var preserved = new List<string>();
        foreach (var relative in stale)
        {
            var target = FullPath(root, relative);
            if (!File.Exists(target))
                continue;

            // The manifest is the owner, but do not delete a file the user replaced with their own.
            if (!await StartsWithGeneratedMarkerAsync(target, cancellationToken))
            {
                preserved.Add(relative);
                continue;
            }

            File.Delete(target);
            deleted.Add(relative);
        }

        var manifest = new Manifest
        {
            Version = ManifestVersion,
            Layout = LayoutName(layout),
            Namespace = @namespace,
            Files = desired.Keys.ToList(),
        };
        var json = JsonSerializer.Serialize(manifest, JsonOptions) + "\n";
        var manifestTemporary = manifestPath + ".tmp-" + Guid.NewGuid().ToString("N");
        await File.WriteAllTextAsync(manifestTemporary, json, new UTF8Encoding(false), cancellationToken);
        File.Move(manifestTemporary, manifestPath, overwrite: true);

        return new GeneratedOutputResult(
            desired.Keys.ToList(),
            deleted,
            preserved);
    }

    public static string LayoutName(GeneratedLayout layout) =>
        layout == GeneratedLayout.Split ? "split" : "single";

    private static async Task<Manifest> ReadManifestAsync(string path, CancellationToken cancellationToken)
    {
        if (!File.Exists(path))
            return new Manifest();

        string json;
        try
        {
            json = await File.ReadAllTextAsync(path, cancellationToken);
        }
        catch (Exception error) when (error is IOException or UnauthorizedAccessException)
        {
            throw new InvalidOperationException($"Could not read the generation manifest '{path}': {error.Message}", error);
        }

        Manifest? manifest;
        try
        {
            manifest = JsonSerializer.Deserialize<Manifest>(json, JsonOptions);
        }
        catch (JsonException error)
        {
            throw new InvalidOperationException(
                $"'{path}' is not a valid Chetah.CodeGen manifest ({error.Message}). "
                + "Delete it if you want to re-adopt the directory without removing previously generated files.",
                error);
        }

        if (manifest is null || manifest.Version != ManifestVersion)
            throw new InvalidOperationException(
                $"'{path}' has an unsupported manifest version. Delete it if you want to re-adopt the directory.");

        manifest.Files = (manifest.Files ?? [])
            .Select(NormalizeRelativePath)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();
        return manifest;
    }

    private static async Task<bool> StartsWithGeneratedMarkerAsync(string path, CancellationToken cancellationToken)
    {
        await using var stream = File.OpenRead(path);
        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true);
        var firstLine = await reader.ReadLineAsync(cancellationToken);
        return string.Equals(firstLine, GeneratedMarker, StringComparison.Ordinal);
    }

    private static string FullPath(string root, string relative) =>
        Path.Combine(root, relative.Replace('/', Path.DirectorySeparatorChar));

    private static string NormalizeRelativePath(string path)
    {
        if (string.IsNullOrWhiteSpace(path))
            throw new InvalidOperationException("A generated file path must not be empty.");

        if (Path.IsPathRooted(path))
            throw new InvalidOperationException($"Generated file path '{path}' must be relative to the output directory.");

        var parts = path.Replace('\\', '/').Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (parts.Length == 0)
            throw new InvalidOperationException($"Generated file path '{path}' must not be empty.");

        foreach (var part in parts)
        {
            if (part is "." or "..")
                throw new InvalidOperationException($"Generated file path '{path}' must stay inside the output directory.");
            if (part.IndexOfAny(InvalidFileNameCharacters) >= 0 || part.Any(char.IsControl))
                throw new InvalidOperationException($"Generated file path '{path}' contains a character that is invalid in a file name.");
            if (part.EndsWith('.') || part.EndsWith(' '))
                throw new InvalidOperationException($"Generated file path '{path}' must not end a path segment with a dot or space.");
            if (ReservedDeviceNames.Contains(part.Split('.')[0]))
                throw new InvalidOperationException($"Generated file path '{path}' uses a reserved Windows device name.");
        }

        return string.Join('/', parts);
    }

    private sealed class Manifest
    {
        public int Version { get; set; }
        public string? Layout { get; set; }
        public string? Namespace { get; set; }
        public List<string>? Files { get; set; }
    }
}
