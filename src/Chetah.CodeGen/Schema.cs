using System.Text.Json;

namespace Chetah.CodeGen;

/// <summary>The CLR type a PostgreSQL column type maps to and how the reader reads it.</summary>
/// <param name="Name">C# type rendered for a NOT NULL column.</param>
/// <param name="NullableName">C# type rendered for a nullable column.</param>
/// <param name="Read">Reader call for a NOT NULL column, with {0} for the ordinal expression.</param>
public sealed record ClrType(string Name, string NullableName, string Read)
{
    public static readonly ClrType Integer = new("int", "int?", "reader.GetInt32({0})");
    public static readonly ClrType BigInt = new("long", "long?", "reader.GetInt64({0})");
    public static readonly ClrType Text = new("string", "string?", "reader.GetString({0})");
    public static readonly ClrType Boolean = new("bool", "bool?", "reader.GetBoolean({0})");
    public static readonly ClrType Uuid = new("Guid", "Guid?", "reader.GetGuid({0})");
    public static readonly ClrType Timestamp = new("DateTime", "DateTime?", "reader.GetDateTime({0})");
}

/// <param name="Id">Chetah's persistent identity for this column, written to the schema file as
/// <c>"$id"</c>. It survives renames; the tool maintains it, users do not need to.</param>
/// <param name="Default">Raw SQL default expression, applied and compared as written.</param>
/// <param name="References">Foreign key target, <c>table.column</c> or <c>schema.table.column</c>.</param>
/// <param name="Unique">A single-column UNIQUE constraint on this column.</param>
/// <param name="Identity">A <c>GENERATED BY DEFAULT AS IDENTITY</c> column (integer types only).</param>
/// <param name="SqlType">Canonical PostgreSQL type as declared, modifier included
/// (<c>varchar(100)</c>, <c>timestamp(3)</c>). Null means "derive it from <paramref name="Type"/>".</param>
public sealed record ColumnSchema(
    string Name,
    ClrType Type,
    bool Nullable,
    long? Id = null,
    string? Default = null,
    string? References = null,
    bool Unique = false,
    bool Identity = false,
    string? SqlType = null)
{
    /// <summary>The type compared against the catalog and written in DDL: the declared canonical
    /// spelling when there is one, otherwise the catalog name implied by the CLR type.</summary>
    public string StorageType => SqlType ?? Type switch
    {
        _ when Type == ClrType.Integer => "int4",
        _ when Type == ClrType.BigInt => "int8",
        _ when Type == ClrType.Text => "text",
        _ when Type == ClrType.Boolean => "bool",
        _ when Type == ClrType.Uuid => "uuid",
        _ when Type == ClrType.Timestamp => "timestamp",
        _ => throw new InvalidOperationException($"No PostgreSQL type mapped for {Type.Name}."),
    };
}

/// <summary>A standalone index declared on a table.</summary>
public sealed record IndexSchema(string Name, IReadOnlyList<string> Columns, bool Unique);

/// <param name="Id">Chetah's persistent identity for this table, written to the schema file as
/// <c>"$id"</c>. It survives renames; the tool maintains it, users do not need to.</param>
/// <param name="PrimaryKey">Primary key columns, in constraint order; composite keys are a list.</param>
/// <param name="Indexes">Standalone indexes to create and keep.</param>
public sealed record TableSchema(
    string Name,
    string ModelName,
    string AccessorName,
    IReadOnlyList<ColumnSchema> Columns,
    long? Id = null,
    IReadOnlyList<string>? PrimaryKey = null,
    IReadOnlyList<IndexSchema>? Indexes = null);

public sealed record Schema(IReadOnlyList<TableSchema> Tables);

/// <summary>Parses and validates the JSON schema file — the single source of truth for
/// generated models and table metadata. An omitted "nullable" means nullable,
/// which matches PostgreSQL's own default.</summary>
public static class SchemaParser
{
    /// <summary>Declared type → CLR type for the generated model, and the canonical PostgreSQL name
    /// used for comparison and DDL. Aliases collapse here so both sides of a diff agree.</summary>
    private static readonly Dictionary<string, (ClrType Type, string Canonical)> Types = new(StringComparer.OrdinalIgnoreCase)
    {
        ["integer"] = (ClrType.Integer, "int4"),
        ["int4"] = (ClrType.Integer, "int4"),
        ["bigint"] = (ClrType.BigInt, "int8"),
        ["int8"] = (ClrType.BigInt, "int8"),
        ["text"] = (ClrType.Text, "text"),
        ["boolean"] = (ClrType.Boolean, "bool"),
        ["bool"] = (ClrType.Boolean, "bool"),
        ["uuid"] = (ClrType.Uuid, "uuid"),
        ["timestamp"] = (ClrType.Timestamp, "timestamp"),
        ["varchar"] = (ClrType.Text, "varchar"),
        ["character varying"] = (ClrType.Text, "varchar"),
    };

    /// <summary>Reads a declared type, including an optional PostgreSQL modifier:
    /// <c>varchar(100)</c>, <c>timestamp(3)</c>. A modifier is only accepted where PostgreSQL accepts
    /// one, so a typo cannot silently declare a different column than the author meant.</summary>
    private static bool TryType(string declared, out ClrType type, out string sqlType, out string? problem)
    {
        type = ClrType.Text;
        sqlType = "";
        problem = null;

        var open = declared.IndexOf('(');
        var name = (open < 0 ? declared : declared[..open]).Trim();
        if (!Types.TryGetValue(name, out var mapped))
        {
            problem = $"unsupported type '{declared}'. Supported: integer, bigint, text, boolean, uuid, "
                + "timestamp, varchar, with a (modifier) where PostgreSQL allows one.";
            return false;
        }

        type = mapped.Type;
        var canonical = mapped.Canonical;

        var modifier = (int?)null;
        if (open >= 0)
        {
            var close = declared.IndexOf(')', open + 1);
            if (close < 0
                || declared[(close + 1)..].Trim().Length > 0
                || !int.TryParse(declared[(open + 1)..close].Trim(), out var parsed))
            {
                problem = $"a malformed type '{declared}'.";
                return false;
            }

            var allowed = canonical switch
            {
                "varchar" => parsed is >= 1 and <= 10_485_760,
                "timestamp" => parsed is >= 0 and <= 6,
                _ => false,
            };

            if (!allowed)
            {
                problem = $"'{declared}', which PostgreSQL does not accept: only varchar takes a length "
                    + "(1-10485760) and timestamp a precision (0-6).";
                return false;
            }

            modifier = parsed;
        }

        sqlType = modifier is null ? canonical : $"{canonical}({modifier})";
        return true;
    }

    public static SchemaParserResult Parse(string json)
    {
        JsonDocument document;
        try
        {
            // JSONC: comments are allowed so schema files can document decisions inline.
            document = JsonDocument.Parse(json, new JsonDocumentOptions { CommentHandling = JsonCommentHandling.Skip });
        }
        catch (JsonException e)
        {
            return SchemaParserResult.Fail($"Schema is not valid JSON: {e.Message}");
        }

        using var disposable = document;
        var root = document.RootElement;

        if (root.ValueKind != JsonValueKind.Object)
            return SchemaParserResult.Fail("Schema root must be an object.");

        if (UnknownProperty(root, "tables") is { } rootProperty)
            return SchemaParserResult.Fail(
                $"Unknown top-level property '{rootProperty}'. The schema contains only \"tables\".");

        if (!root.TryGetProperty("tables", out var tablesElement) || tablesElement.ValueKind != JsonValueKind.Object)
            return SchemaParserResult.Fail("Schema must contain a \"tables\" object keyed by table name.");

        var tables = new List<TableSchema>();
        var tableNames = new HashSet<string>(StringComparer.Ordinal);
        var csharpNames = new HashSet<string>(StringComparer.OrdinalIgnoreCase) { "ChetahSchema", "Bindings" };
        // Identity is global: one id names one object, whether it is a table or a column.
        var objectIds = new HashSet<long>();
        // Index names share the schema namespace in PostgreSQL.
        var indexNames = new HashSet<string>(StringComparer.Ordinal);

        foreach (var tableProperty in tablesElement.EnumerateObject())
        {
            var tableName = tableProperty.Name;

            if (tableName.Length == 0)
                return SchemaParserResult.Fail("Table names must not be empty.");

            if (!tableNames.Add(tableName))
                return SchemaParserResult.Fail($"Table '{tableName}' is defined more than once.");

            var tableElement = tableProperty.Value;
            if (tableElement.ValueKind != JsonValueKind.Object)
                return SchemaParserResult.Fail($"Table '{tableName}' must be an object.");

            if (UnknownProperty(tableElement, "$id", "model", "columns", "primaryKey", "indexes") is { } tableEntryProperty)
                return SchemaParserResult.Fail(
                    $"Table '{tableName}': unknown property '{tableEntryProperty}'. Allowed properties: "
                    + "\"$id\", \"model\", \"columns\", \"primaryKey\", \"indexes\".");

            if (!TryPositiveId(tableElement, out var tableId))
                return SchemaParserResult.Fail($"Table '{tableName}': \"$id\" must be a positive integer.");

            if (tableId is { } tableIdentity && !objectIds.Add(tableIdentity))
                return SchemaParserResult.Fail(
                    $"Table '{tableName}': \"$id\" {tableIdentity} is already used by another object. Ids identify one object forever; "
                    + "delete the duplicated \"$id\" so a fresh one is allocated.");

            var accessorName = PascalCase(tableName) + "Table";

            if (!IsValidIdentifier(accessorName))
                return SchemaParserResult.Fail($"Table '{tableName}': table name cannot produce a valid C# accessor class name ('{accessorName}'). Use letters, digits, underscores or hyphens in the table name.");

            if (!TryNonEmptyString(tableElement, "model", out var modelName))
                modelName = PascalCase(tableName);

            if (!IsValidIdentifier(modelName))
                return SchemaParserResult.Fail($"Table '{tableName}': model name '{modelName}' is not a valid C# identifier.");

            foreach (var name in new[] { accessorName, modelName })
            {
                if (!csharpNames.Add(name))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': generated name '{name}' is already used by another table. "
                        + "Set an explicit \"model\" name.");
            }

            if (!tableElement.TryGetProperty("columns", out var columnsElement) || columnsElement.ValueKind != JsonValueKind.Object)
                return SchemaParserResult.Fail($"Table '{tableName}' must contain a \"columns\" object keyed by column name.");

            var columns = new List<ColumnSchema>();
            var columnNames = new HashSet<string>(StringComparer.Ordinal);
            // Generated C# property names must also be unique: "user_id" and
            // "userId" would otherwise emit the same member twice.
            var propertyNames = new Dictionary<string, string>(StringComparer.Ordinal);

            foreach (var columnProperty in columnsElement.EnumerateObject())
            {
                var columnName = columnProperty.Name;

                if (columnName.Length == 0)
                    return SchemaParserResult.Fail($"Table '{tableName}': column names must not be empty.");

                if (!columnNames.Add(columnName))
                    return SchemaParserResult.Fail($"Table '{tableName}': column '{columnName}' is defined more than once.");

                var columnElement = columnProperty.Value;
                if (columnElement.ValueKind != JsonValueKind.Object)
                    return SchemaParserResult.Fail($"Table '{tableName}': column '{columnName}' must be an object.");

                if (UnknownProperty(columnElement, "$id", "type", "nullable", "unique", "references", "default", "identity") is { } columnEntryProperty)
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' has unknown property '{columnEntryProperty}'. "
                        + "Allowed properties: \"$id\", \"type\", \"nullable\", \"unique\", \"references\", \"default\", \"identity\".");

                if (!TryPositiveId(columnElement, out var columnId))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}': \"$id\" must be a positive integer.");

                if (columnId is { } columnIdentity && !objectIds.Add(columnIdentity))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}': \"$id\" {columnIdentity} is already used by another object. "
                        + "Ids identify one object forever; delete the duplicated \"$id\" so a fresh one is allocated.");

                if (!IsValidIdentifier(columnName))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column name '{columnName}' is not a plain identifier "
                        + "(letters, digits, underscores; must not start with a digit). Renaming the column may be simpler.");

                var propertyName = PascalCase(columnName);
                if (!IsValidIdentifier(propertyName))
                    return SchemaParserResult.Fail($"Table '{tableName}': column '{columnName}' cannot produce a valid C# property name. Rename the column.");

                if (propertyNames.TryGetValue(propertyName, out var firstColumn))
                    return SchemaParserResult.Fail($"Table '{tableName}': columns '{firstColumn}' and '{columnName}' both map to the C# property '{propertyName}'. Rename one of them.");
                propertyNames.Add(propertyName, columnName);

                if (!TryNonEmptyString(columnElement, "type", out var typeName))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' must declare a \"type\" string.");

                if (!TryType(typeName, out var type, out var sqlType, out var typeProblem))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' has {typeProblem}.");

                var nullable = true;
                if (columnElement.TryGetProperty("nullable", out var nullableValue))
                {
                    if (nullableValue.ValueKind is not (JsonValueKind.True or JsonValueKind.False))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': column '{columnName}' has a non-boolean \"nullable\" value; use true or false.");

                    nullable = nullableValue.ValueKind == JsonValueKind.True;
                }

                if (!TryBoolean(columnElement, "unique", out var unique))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' has a non-boolean \"unique\" value; use true or false.");

                if (!TryBoolean(columnElement, "identity", out var identity))
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' has a non-boolean \"identity\" value; use true or false.");

                string? columnDefault = null;
                if (columnElement.TryGetProperty("default", out var defaultElement))
                {
                    if (defaultElement.ValueKind != JsonValueKind.String || string.IsNullOrWhiteSpace(defaultElement.GetString()))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': column '{columnName}': \"default\" must be a non-empty SQL expression string.");

                    columnDefault = defaultElement.GetString()!.Trim();
                }

                string? references = null;
                if (columnElement.TryGetProperty("references", out var referencesElement))
                {
                    if (referencesElement.ValueKind != JsonValueKind.String || !IsReference(referencesElement.GetString()!))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': column '{columnName}': \"references\" must be \"table.column\" "
                            + "or \"schema.table.column\".");

                    references = referencesElement.GetString();
                }

                if (identity && type != ClrType.Integer && type != ClrType.BigInt)
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}': \"identity\" requires an integer or bigint column.");

                if (identity && columnDefault is not null)
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': column '{columnName}' cannot have both \"identity\" and \"default\".");

                columns.Add(new ColumnSchema(
                    columnName,
                    type,
                    nullable,
                    columnId,
                    columnDefault,
                    references,
                    unique,
                    identity,
                    sqlType));
            }

            if (columns.Count == 0)
                return SchemaParserResult.Fail($"Table '{tableName}' must define at least one column.");

            var primaryKey = new List<string>();
            if (tableElement.TryGetProperty("primaryKey", out var primaryKeyElement))
            {
                if (primaryKeyElement.ValueKind != JsonValueKind.Array)
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': \"primaryKey\" must be an array of column names.");

                foreach (var entry in primaryKeyElement.EnumerateArray())
                {
                    if (entry.ValueKind != JsonValueKind.String || string.IsNullOrEmpty(entry.GetString()))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': \"primaryKey\" must contain column names.");

                    var keyColumn = entry.GetString()!;
                    if (primaryKey.Contains(keyColumn))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': \"primaryKey\" lists column '{keyColumn}' twice.");

                    if (!columnNames.Contains(keyColumn))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': \"primaryKey\" names column '{keyColumn}', which is not declared.");

                    primaryKey.Add(keyColumn);
                }
            }

            var indexes = new List<IndexSchema>();
            if (tableElement.TryGetProperty("indexes", out var indexesElement))
            {
                if (indexesElement.ValueKind != JsonValueKind.Object)
                    return SchemaParserResult.Fail(
                        $"Table '{tableName}': \"indexes\" must be an object keyed by index name.");

                foreach (var indexProperty in indexesElement.EnumerateObject())
                {
                    var indexName = indexProperty.Name;
                    if (!IsValidIdentifier(indexName))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index name '{indexName}' is not a plain identifier.");

                    if (!indexNames.Add(indexName))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index '{indexName}' is declared more than once. "
                            + "Index names are unique within a schema.");

                    var indexElement = indexProperty.Value;
                    if (indexElement.ValueKind != JsonValueKind.Object)
                        return SchemaParserResult.Fail($"Table '{tableName}': index '{indexName}' must be an object.");

                    if (UnknownProperty(indexElement, "columns", "unique") is { } indexEntryProperty)
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index '{indexName}' has unknown property '{indexEntryProperty}'. "
                            + "Allowed properties: \"columns\", \"unique\".");

                    if (!indexElement.TryGetProperty("columns", out var indexColumnsElement)
                        || indexColumnsElement.ValueKind != JsonValueKind.Array)
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index '{indexName}' must declare a \"columns\" array.");

                    var indexColumns = new List<string>();
                    foreach (var entry in indexColumnsElement.EnumerateArray())
                    {
                        if (entry.ValueKind != JsonValueKind.String || string.IsNullOrEmpty(entry.GetString()))
                            return SchemaParserResult.Fail(
                                $"Table '{tableName}': index '{indexName}' must list column names.");

                        var indexColumn = entry.GetString()!;
                        if (indexColumns.Contains(indexColumn))
                            return SchemaParserResult.Fail(
                                $"Table '{tableName}': index '{indexName}' lists column '{indexColumn}' twice.");

                        if (!columnNames.Contains(indexColumn))
                            return SchemaParserResult.Fail(
                                $"Table '{tableName}': index '{indexName}' names column '{indexColumn}', which is not declared.");

                        indexColumns.Add(indexColumn);
                    }

                    if (indexColumns.Count == 0)
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index '{indexName}' must list at least one column.");

                    if (!TryBoolean(indexElement, "unique", out var uniqueIndex))
                        return SchemaParserResult.Fail(
                            $"Table '{tableName}': index '{indexName}' has a non-boolean \"unique\" value; use true or false.");

                    indexes.Add(new IndexSchema(indexName, indexColumns, uniqueIndex));
                }
            }

            tables.Add(new TableSchema(
                tableName,
                modelName,
                accessorName,
                columns,
                tableId,
                primaryKey.Count == 0 ? null : primaryKey,
                indexes.Count == 0 ? null : indexes));
        }

        if (tables.Count == 0)
            return SchemaParserResult.Fail("Schema must define at least one table.");

        return SchemaParserResult.Ok(new Schema(tables));
    }

    /// <summary>First property outside <paramref name="allowed"/>, or null when every property is known.
    /// Rejecting unknown keys turns a typo into a schema error instead of a silently ignored setting.</summary>
    private static string? UnknownProperty(JsonElement element, params string[] allowed)
    {
        foreach (var property in element.EnumerateObject())
        {
            if (!allowed.Contains(property.Name, StringComparer.Ordinal))
                return property.Name;
        }
        return null;
    }

    /// <summary>Reads an optional <c>"$id"</c>. False means it is present but not a positive integer.</summary>
    private static bool TryPositiveId(JsonElement element, out long? value)
    {
        value = null;
        if (!element.TryGetProperty("$id", out var id))
            return true;

        if (id.ValueKind != JsonValueKind.Number || !id.TryGetInt64(out var parsed) || parsed <= 0)
            return false;

        value = parsed;
        return true;
    }

    /// <summary>Reads an optional boolean. False means it is present but not true/false.</summary>
    private static bool TryBoolean(JsonElement element, string property, out bool value)
    {
        value = false;
        if (!element.TryGetProperty(property, out var member))
            return true;

        if (member.ValueKind is not (JsonValueKind.True or JsonValueKind.False))
            return false;

        value = member.ValueKind == JsonValueKind.True;
        return true;
    }

    /// <summary><c>table.column</c> or <c>schema.table.column</c>, each part a plain identifier.</summary>
    private static bool IsReference(string value)
    {
        var parts = value.Split('.');
        return parts.Length is 2 or 3 && parts.All(IsValidIdentifier);
    }

    private static bool TryNonEmptyString(JsonElement element, string property, out string value)
    {
        value = "";
        if (element.TryGetProperty(property, out var v) && v.ValueKind == JsonValueKind.String)
        {
            value = v.GetString()!;
            return value.Length > 0;
        }
        return false;
    }

    /// <summary>Singular-safe default naming: "users" → "Users", "user_profiles" → "UserProfile".</summary>
    public static string PascalCase(string identifier)
    {
        // Underscores and SQL-legal hyphens both act as word boundaries.
        var parts = identifier.Split(new[] { '_', '-' }, StringSplitOptions.RemoveEmptyEntries);
        return string.Concat(parts.Select(p => p.Length == 0
            ? ""
            : string.Concat(char.ToUpperInvariant(p[0]), p[1..].ToLowerInvariant())));
    }

    private static bool IsValidIdentifier(string name) =>
        name.Length > 0
        && (char.IsLetter(name[0]) || name[0] == '_')
        && name.All(c => char.IsLetterOrDigit(c) || c == '_');
}

public sealed record SchemaParserResult(Schema? Schema, string? Error)
{
    public static SchemaParserResult Ok(Schema schema) => new(schema, null);
    public static SchemaParserResult Fail(string error) => new(null, error);
}
